// callback function that will be executed when data is received
void OnDataRecv(const uint8_t * mac, const uint8_t *incomingData, int len) {
  lastDataTime=millis();
  if (!wifi){
    wifi=true;
    drawMSG();
  }
 memcpy(&prevCarStatus, &carStatus, sizeof(carStatus));
  memcpy(&carStatus, incomingData, sizeof(carStatus));
  if ( !memcmp(&carStatus, &prevCarStatus, sizeof(prevCarStatus)) == 0 ){

    if(carStatus.can != prevCarStatus.can){
      drawCAN();
    }
    if(carStatus.temp != prevCarStatus.temp){
      drawCoolantTemp();
    }
    if(carStatus.odo != prevCarStatus.odo){
      drawOdometer();
    }
    if(carStatus.obdii != prevCarStatus.obdii){
      drawOBD();
    }
    if(carStatus.oilPressure != prevCarStatus.oilPressure){
      drawOilPressure();
      Serial.print(carStatus.oilPressure);

    }
    //Serial.print("data changed");
  }
  else {

    //Serial.print("data NOT changed");
  }
  g_rpm = carStatus.rpm;
  //g_engine_temperature = carStatus.temp;
  g_fuel=carStatus.fuel;//carStatus.fuel;
  g_speed=carStatus.speed;
  //updateScreen();
}

void setup()
{

 Serial.begin(115200);
 Serial.setTimeout(250);
  Serial.println(" CAN...............INIT");
  CAN0.setCANPins(GPIO_NUM_4, GPIO_NUM_5); //config for shield v1.3+, see important note above!
  CAN0.begin(100000); // 100Kbps
  Serial.println(" CAN............100Kbps");

  //delay(2000);

 // Set device as a Wi-Fi Station
  WiFi.mode(WIFI_STA);

  // Init ESP-NOW
  if (esp_now_init() != ESP_OK) {
    Serial.println("Error initializing ESP-NOW");
    return;
  }
  
  //screen stuff
  tft.init(240, 320, SPI_MODE2);    // Init ST7789 display 135x240 pixel
  tft.setRotation(1);
  tft.fillScreen(ST77XX_BLACK);
  tft.invertDisplay(false);
  animate();
  tft.setFont(&FreeSans12pt7b);
  tft.setTextSize(1);
  updateScreen();


  // Once ESPNow is successfully Init, we will register for recv CB to
  // get recv packer info
  esp_now_register_recv_cb(esp_now_recv_cb_t(OnDataRecv));


}

